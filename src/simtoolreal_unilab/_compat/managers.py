"""Manager logging views and the row-scoped observation dispatch.

Method bodies below are ported verbatim from the SimToolReal development
branch of UniLab and applied onto the pinned official classes at import time
(see simtoolreal_unilab._compat). They exec() inside a copy of the official
module namespace so module-level helpers resolve exactly as upstream wrote
them.
"""
from __future__ import annotations

from typing import Any  # noqa: F401

import numpy as np  # noqa: F401
from unilab.managers import command_manager as _command_module
from unilab.managers import observation_manager as _observation_module
from unilab.managers import reward_manager as _reward_module

_SOURCES = {
    "RewardManager.step_reward_vectors": (
        '    def step_reward_vectors(self) -> dict[str, np.ndarray]:\n'
        '        """Return the latest weighted per-environment reward terms.\n'
        '\n'
        '        This is a read-only logging view.  The arrays are owned by the manager\n'
        '        and are valid until the next ``compute()`` call.  Task compatibility\n'
        "        loggers use this to reproduce the original RL-Games observer's\n"
        '        per-environment episode accumulation without changing the reward path.\n'
        '        """\n'
        '        return {\n'
        '            name: self._step_reward[:, term_idx]\n'
        '            for term_idx, name in enumerate(self._term_names)\n'
        '        }\n'
    ),

    "CommandManager.log_extras": (
        '    def log_extras(self, *, reward_manager, termination_manager) -> dict[str, Any]:\n'
        '        """Collect optional task-owned compatibility logging views.\n'
        '\n'
        '        Manager terms remain responsible for task-specific names and state\n'
        '        mapping.  The hook is intentionally read-only and optional so generic\n'
        '        manager-based tasks do not pay for or depend on SimToolReal logging.\n'
        '        """\n'
        '        extras: dict[str, Any] = {}\n'
        '        for term in self._terms.values():\n'
        '            hook = getattr(term, "log_extras", None)\n'
        '            if hook is None:\n'
        '                continue\n'
        '            values = hook(\n'
        '                reward_manager=reward_manager,\n'
        '                termination_manager=termination_manager,\n'
        '            )\n'
        '            if values:\n'
        '                extras.update(values)\n'
        '        return extras\n'
    ),
}
_COMPUTE_GROUP_SOURCE = (
    '    def compute_group(\n'
    '        self,\n'
    '        group_name: str,\n'
    '        update_history: bool = False,\n'
    '        env_ids: np.ndarray | None = None,\n'
    '        *,\n'
    '        share_cache: dict[tuple, np.ndarray] | None = None,\n'
    '    ) -> np.ndarray | dict[str, np.ndarray]:\n'
    '        group_cfg = self.cfg[group_name]\n'
    '        if group_cfg is None:\n'
    '            raise KeyError(f"Observation group \'{group_name}\' is disabled.")\n'
    '        group_term_names = self._group_obs_term_names[group_name]\n'
    '        group_obs: dict[str, np.ndarray] = {}\n'
    '        obs_terms = zip(group_term_names, self._group_obs_term_cfgs[group_name], strict=False)\n'
    '        if share_cache is None:\n'
    '            share_cache = {}\n'
    '        share_map = self._group_obs_term_share.get(group_name, {})\n'
    '        # In the strict default policy a finite result is by far the common\n'
    '        # case.  For concatenated groups, scan the assembled output once and\n'
    '        # only inspect individual slices when an error is actually found; this\n'
    '        # retains the per-term diagnostic while removing repeated full scans\n'
    '        # from the hot path.\n'
    '        defer_error_nan_check = (\n'
    '            self._group_obs_concatenate[group_name]\n'
    '            and not self._group_obs_temporal[group_name]\n'
    '            and group_cfg.nan_check_per_term\n'
    '            and group_cfg.nan_policy == "error"\n'
    '        )\n'
    '        # Reset path (issue #1259 R2): when no term in this group uses delay or\n'
    '        # history buffers, everything downstream of the term call is row\n'
    '        # independent, so only the reset rows are processed. Legacy term calls\n'
    '        # stay full-batch and are sliced here; terms with the optional\n'
    '        # compute_rows() capability select rows before expensive computation.\n'
    '        # Noise is drawn for the reset rows only — issue #1349 removed the\n'
    '        # full-batch RNG-stream parity requirement.\n'
    '        row_scoped = env_ids is not None and not self._group_obs_temporal[group_name]\n'
    '        for term_name, term_cfg in obs_terms:\n'
    '            share_key = share_map.get(term_name)\n'
    '            row_term = row_scoped and callable(getattr(term_cfg.func, "compute_rows", None))\n'
    '            if share_key is not None and share_key in share_cache:\n'
    '                obs = share_cache[share_key]\n'
    '            else:\n'
    '                if row_term:\n'
    '                    obs = term_cfg.func.compute_rows(\n'
    '                        self._env, env_ids=np.asarray(env_ids), **term_cfg.params\n'
    '                    )\n'
    '                else:\n'
    '                    obs = term_cfg.func(self._env, **term_cfg.params)\n'
    '                if share_key is not None:\n'
    '                    share_cache[share_key] = obs\n'
    '            if not isinstance(obs, np.ndarray):\n'
    '                raise TypeError(\n'
    '                    f"ObservationManager term \'{group_name}/{term_name}\' returned "\n'
    '                    f"{type(obs).__name__}, expected np.ndarray."\n'
    '                )\n'
    '            expected_rows = self.num_envs if not row_term else len(np.asarray(env_ids))\n'
    '            if obs.ndim < 2 or obs.shape[0] != expected_rows:\n'
    '                raise ValueError(\n'
    '                    f"ObservationManager term \'{group_name}/{term_name}\' returned shape "\n'
    '                    f"{obs.shape}, expected ({expected_rows}, ...) with num_envs={self.num_envs}."\n'
    '                )\n'
    '            fresh = False\n'
    '            if row_scoped and not row_term:\n'
    '                # Slice before noise: reset-path noise is drawn for the reset\n'
    '                # rows only (issue #1349 removed the full-batch RNG-stream\n'
    '                # parity requirement). Fancy indexing already returns a fresh\n'
    '                # row copy, safe for the in-place clip/scale below.\n'
    '                obs = obs[env_ids]\n'
    '                fresh = True\n'
    '            elif row_term:\n'
    '                # A term with an explicit row-scoped implementation already\n'
    '                # returned only env_ids rows; do not slice it a second time.\n'
    '                fresh = True\n'
    '            if isinstance(term_cfg.noise, noise_cfg.NoiseCfg):\n'
    '                # NoiseCfg.apply always returns a newly allocated array.\n'
    '                obs = term_cfg.noise.apply(obs, rng=self._env.rng)\n'
    '                fresh = True\n'
    '            elif isinstance(term_cfg.noise, noise_cfg.NoiseModelCfg):\n'
    '                # NoiseModel.__call__ likewise returns a new array.\n'
    '                obs = self._group_obs_class_instances[group_name][term_name](obs)\n'
    '                fresh = True\n'
    '            sanitizes_per_term = group_cfg.nan_check_per_term and group_cfg.nan_policy in (\n'
    '                "warn",\n'
    '                "sanitize",\n'
    '            )\n'
    '            exposes_term_output = (\n'
    '                not self._group_obs_concatenate[group_name]\n'
    '                and term_cfg.delay_max_lag == 0\n'
    '                and term_cfg.history_length == 0\n'
    '            )\n'
    '            if (\n'
    '                not row_scoped\n'
    '                and not fresh\n'
    '                and (\n'
    '                    term_cfg.clip is not None\n'
    '                    or term_cfg.scale is not None\n'
    '                    or sanitizes_per_term\n'
    '                    or exposes_term_output\n'
    '                )\n'
    '            ):\n'
    '                # Concatenation and temporal buffers already copy their inputs.\n'
    '                # Only take a defensive copy when this pipeline may mutate the\n'
    '                # term or expose it directly to callers.\n'
    '                obs = obs.copy()\n'
    '            if term_cfg.clip:\n'
    '                np.clip(obs, term_cfg.clip[0], term_cfg.clip[1], out=obs)\n'
    '            if term_cfg.scale is not None:\n'
    '                scale = term_cfg.scale\n'
    '                assert isinstance(scale, np.ndarray)\n'
    '                np.multiply(obs, scale, out=obs)\n'
    '\n'
    '            # Check for NaN/Inf before delay/history buffers (per-term checking).\n'
    '            if (\n'
    '                group_cfg.nan_check_per_term\n'
    '                and group_cfg.nan_policy != "disabled"\n'
    '                and not defer_error_nan_check\n'
    '            ):\n'
    '                obs = self._check_and_handle_nans(\n'
    '                    obs,\n'
    '                    context=f"{group_name}/{term_name}",\n'
    '                    policy=group_cfg.nan_policy,\n'
    '                    env_ids=env_ids if row_scoped else None,\n'
    '                )\n'
    '\n'
    '            if term_cfg.delay_max_lag > 0:\n'
    '                delay_buffer = self._group_obs_term_delay_buffer[group_name][term_name]\n'
    '                if env_ids is None or not delay_buffer.is_initialized:\n'
    '                    delay_buffer.append(obs)\n'
    '                    obs = delay_buffer.compute()\n'
    '                else:\n'
    '                    delay_buffer.backfill(obs, env_ids)\n'
    '                    obs = delay_buffer.peek()\n'
    '            if term_cfg.history_length > 0:\n'
    '                circular_buffer = self._group_obs_term_history_buffer[group_name][term_name]\n'
    '                if env_ids is None or not circular_buffer.is_initialized:\n'
    '                    if update_history or not circular_buffer.is_initialized:\n'
    '                        circular_buffer.append(obs)\n'
    '                else:\n'
    '                    circular_buffer.backfill(obs, env_ids)\n'
    '\n'
    '                if term_cfg.flatten_history_dim:\n'
    '                    group_obs[term_name] = circular_buffer.buffer.reshape(self._env.num_envs, -1)\n'
    '                else:\n'
    '                    group_obs[term_name] = circular_buffer.buffer\n'
    '            else:\n'
    '                group_obs[term_name] = obs\n'
    '\n'
    '        # Final NaN check for non-per-term checking.\n'
    '        if not group_cfg.nan_check_per_term and group_cfg.nan_policy != "disabled":\n'
    '            if self._group_obs_concatenate[group_name]:\n'
    '                # Will check after concatenation below.\n'
    '                pass\n'
    '            else:\n'
    '                for term_name in group_obs:\n'
    '                    group_obs[term_name] = self._check_and_handle_nans(\n'
    '                        group_obs[term_name],\n'
    '                        context=f"{group_name}/{term_name}",\n'
    '                        policy=group_cfg.nan_policy,\n'
    '                        env_ids=env_ids if row_scoped else None,\n'
    '                    )\n'
    '\n'
    '        if self._group_obs_concatenate[group_name]:\n'
    '            result = np.concatenate(\n'
    '                list(group_obs.values()), axis=self._group_obs_concatenate_dim[group_name]\n'
    '            )\n'
    '            if defer_error_nan_check:\n'
    '                finite = np.isfinite(result)\n'
    '                if not finite.all():\n'
    '                    axis = self._group_obs_concatenate_dim[group_name]\n'
    '                    axis = axis if axis >= 0 else result.ndim + axis\n'
    '                    offset = 0\n'
    '                    for term_name, term_dims in zip(\n'
    '                        group_term_names,\n'
    '                        self._group_obs_term_dim[group_name],\n'
    '                        strict=True,\n'
    '                    ):\n'
    '                        width = int(term_dims[axis - 1])\n'
    '                        selectors = [slice(None)] * result.ndim\n'
    '                        selectors[axis] = slice(offset, offset + width)\n'
    '                        selector = tuple(selectors)\n'
    '                        if not finite[selector].all():\n'
    '                            # Reuse the established diagnostic path so the\n'
    '                            # error still names the first offending term and\n'
    '                            # reports reset-row IDs when applicable.\n'
    '                            self._check_and_handle_nans(\n'
    '                                result[selector],\n'
    '                                context=f"{group_name}/{term_name}",\n'
    '                                policy=group_cfg.nan_policy,\n'
    '                                env_ids=env_ids if row_scoped else None,\n'
    '                            )\n'
    '                            break\n'
    '                        offset += width\n'
    '            # Final check for concatenated result (non-per-term checking).\n'
    '            if not group_cfg.nan_check_per_term and group_cfg.nan_policy != "disabled":\n'
    '                result = self._check_and_handle_nans(\n'
    '                    result,\n'
    '                    context=group_name,\n'
    '                    policy=group_cfg.nan_policy,\n'
    '                    env_ids=env_ids if row_scoped else None,\n'
    '                )\n'
    '        else:\n'
    '            result = group_obs\n'
    '\n'
    '        if env_ids is not None and not row_scoped:\n'
    '            # Groups with delay/history terms ran the full-batch pipeline above\n'
    '            # (buffer readout stays full-batch); slice the reset rows to match\n'
    '            # the reset-path return contract.\n'
    '            if isinstance(result, dict):\n'
    '                result = {name: values[env_ids] for name, values in result.items()}\n'
    '            else:\n'
    '                result = result[env_ids]\n'
    '\n'
    '        return result\n'
)


def apply() -> None:
    reward_ns = dict(vars(_reward_module))
    for name, source in _SOURCES.items():
        exec(compile(source, f"<compat.managers.{{name}}>", "exec"), reward_ns)
    setattr(_reward_module.RewardManager, "step_reward_vectors", reward_ns["step_reward_vectors"])
    command_ns = dict(vars(_command_module))
    for name, source in _SOURCES.items():
        exec(compile(source, f"<compat.managers.{{name}}>", "exec"), command_ns)
    setattr(
        _command_module.CommandManager,
        "log_extras",
        command_ns["log_extras"],
    )
    observation_ns = dict(vars(_observation_module))
    exec(
        compile(_COMPUTE_GROUP_SOURCE, "<compat.managers.compute_group>", "exec"),
        observation_ns,
    )
    setattr(_observation_module.ObservationManager, "compute_group", observation_ns["compute_group"])
